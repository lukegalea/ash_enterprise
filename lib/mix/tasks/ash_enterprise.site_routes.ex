defmodule Mix.Tasks.AshEnterprise.SiteRoutes do
  @shortdoc "Write docs/routes.json, the routes the public site may name, from the router"

  @moduledoc """
  Writes `docs/routes.json` from `AshEnterpriseWeb.Router`, so the public site
  names the application's routes from data instead of by hand.

      mix ash_enterprise.site_routes           # rewrite docs/routes.json
      mix ash_enterprise.site_routes --check   # fail if it is out of date

  It runs in the test environment (`preferred_envs` in mix.exs): the routes
  behind `:dev_routes` (the dashboard, the admin, clarity, the canvas, the two
  API explorers) are not compiled there, so the file lists what a release serves.

  `test/ash_enterprise/site_data_test.exs` compares the file with the router on
  every CI run. A route added or removed fails that test until this task is run
  and the file committed with the change.

  The router is read with `Phoenix.Router.routes/1`, after compiling. Nothing is
  started.
  """

  use Mix.Task

  @requirements ["compile"]

  @path "docs/routes.json"

  @impl Mix.Task
  def run(argv) do
    {opts, _rest} = OptionParser.parse!(argv, strict: [check: :boolean])

    if Mix.env() != :test do
      Mix.raise("""
      Run this task in the test environment: MIX_ENV=test mix ash_enterprise.site_routes.
      Other environments compile the dev-only routes, which a release does not serve.
      """)
    end

    rendered = render()
    current = if File.exists?(@path), do: File.read!(@path)

    cond do
      Keyword.get(opts, :check, false) and current != rendered ->
        Mix.shell().error(
          "#{@path} is out of date with the router. Run `mix ash_enterprise.site_routes` and commit the result."
        )

        exit({:shutdown, 1})

      Keyword.get(opts, :check, false) ->
        Mix.shell().info("#{@path} matches the router.")

      current == rendered ->
        Mix.shell().info("Unchanged #{@path}")

      true ->
        File.write!(@path, rendered)
        Mix.shell().info("Rewrote #{@path}")
    end
  end

  @doc "The relative path of the generated file."
  @spec path() :: String.t()
  def path, do: @path

  @doc "The file's content: the router's routes as pretty JSON, sorted by path and verb."
  @spec render() :: String.t()
  def render do
    %{
      "$comment" => [
        "Generated by `MIX_ENV=test mix ash_enterprise.site_routes` from AshEnterpriseWeb.Router.",
        "Do not edit by hand. Dev-only routes are not listed. The public site reads this file."
      ],
      "routes" => routes()
    }
    |> Jason.encode!(pretty: true)
    |> Kernel.<>("\n")
  end

  @doc "Every route the router compiles in this environment, as plain maps."
  @spec routes() :: [map()]
  def routes do
    AshEnterpriseWeb.Router
    |> Phoenix.Router.routes()
    |> Enum.map(&describe/1)
    |> Enum.uniq()
    |> Enum.sort_by(&{&1["path"], &1["verb"]})
  end

  defp describe(%{metadata: %{phoenix_live_view: {live, action, _opts, _extra}}} = route) do
    %{
      "verb" => verb(route.verb),
      "path" => route.path,
      "kind" => "live",
      "module" => name(live),
      "action" => action(action)
    }
  end

  defp describe(route) do
    %{
      "verb" => verb(route.verb),
      "path" => route.path,
      "kind" => if(route.verb == :*, do: "forward", else: "controller"),
      "module" => name(route.plug),
      "action" => action(route.plug_opts)
    }
  end

  defp verb(:*), do: "*"
  defp verb(verb), do: verb |> to_string() |> String.upcase()

  defp name(module) when is_atom(module), do: module |> Module.split() |> Enum.join(".")

  defp action(nil), do: nil
  defp action(action) when is_atom(action), do: to_string(action)
  defp action(_opts), do: nil
end
