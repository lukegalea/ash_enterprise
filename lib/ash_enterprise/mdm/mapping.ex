defmodule AshEnterprise.Mdm.Mapping do
  @moduledoc """
  A versioned schema mapping (ingress or egress), macro-generated by
  `AshMdm.Resources` on the platform base.

  Configuration-as-data for the no-deploy guarantee (ADR 0050): a new
  customer schema is onboarded by authoring and activating one of these —
  through the code interface or the ImportLive UI — never by a release.
  Activation supersedes; `audit?` stays on because who changed a mapping is
  provenance the operator's model must answer for.

  The `:activate` action is person-gated: mapping activation is a human
  decision even when the field rules were machine-proposed (the MDM-8
  proposal path drafts, never activates).
  """

  use AshEnterprise.Platform.Resource,
    domain: AshEnterprise.Mdm,
    ownership: :organization_owned,
    lifecycle?: false,
    archival?: false,
    policies?: false

  use AshMdm.Resources,
      {:mapping, repo: AshEnterprise.Repo, table: "mdm_mappings", tenant?: true}

  policies do
    # `policies?: false` is deliberate (the HumanVerdict drill): the
    # inherited set opens with `bypass SystemActor`, which would let a
    # system actor reach :activate past any later gate. Mapping activation
    # is a person's decision even when the field rules were machine-proposed
    # (MDM-8 drafts, never activates) — so the set is declared here, with
    # the activation gate FIRST and positive (a user row, not "not a
    # system actor", so a future actor kind fails closed).
    policy action(:activate) do
      authorize_if AshEnterprise.SystemOne.Checks.PersonActor
    end

    # Everything else follows the platform convention: the engine bypasses,
    # then the two grant paths.
    bypass AshBpmn.Checks.AshBpmnInteraction do
      authorize_if always()
    end

    bypass AshDecisions.Checks.AshDecisionsInteraction do
      authorize_if always()
    end

    bypass AshEnterprise.Security.Checks.SystemActor do
      authorize_if always()
    end

    policy always() do
      authorize_if AshEnterprise.Security.Checks.RoleGrant
      authorize_if AshEnterprise.Security.Checks.SharedWithActor
      authorize_if AshEnterprise.Security.Checks.HierarchyGrant
    end
  end
end
