defmodule AshEnterprise.BusinessEvents.Ledger do
  @moduledoc """
  The business-event ledger (ADR 0051): `ash_discrete_business_events`'
  `:ledger` macro, instantiated on the platform base.

  Every row is one discrete business fact derived from the canonical store
  (`AshEnterprise.BusinessEvents.Derivation`): a calendar event scheduled,
  changed or cancelled; a message received or sent; a conversation started.
  The package supplies the machinery — the per-region advisory lock taken
  before insert (so `sequence` is commit order within a region), the
  per-region SHA-256 chain written by a trigger, the immutability trigger,
  delivery idempotency, the region-scoped reads and the commit-order feed.
  `record` is the only write path; there is no update and no destroy.

  ## Owner-only, tenant-scoped

  A platform resource like any other: `organization_id` and attribute
  multitenancy, `:user_owned`. Each row is owned by the owner of the
  canonical row it was derived from, and the resource is owner-only
  (`AshEnterprise.Security.Privilege.owner_only?/1`), as
  `AshEnterprise.Canonical.Message` is: a person's event stream is about their
  own mail, Slack and calendar, so no role reaches another user's rows.

  The owner arrives inside the `context` argument (`"owner"`), which is one
  of the chained columns, so who an event belongs to is covered by the chain
  — `AshEnterprise.BusinessEvents.Changes.StampOwner` copies it into the
  ownership columns. The tenant arrives as the `record` call's tenant and is
  mirrored into the same `context` map for the same reason.

  ## What a row may carry (ADR 0051, ADR 0024)

  Only what the canonical row it was derived from holds **in the clear**:
  ids, timestamps, statuses, directions. Never a sealed field, and never a
  digest of one — a hash of a short title is a dictionary away from the
  title, and it would outlive the shred. So shredding an erasure scope
  changes nothing here: the chain stays verifiable because no chained byte
  depended on the destroyed key, and nothing readable is left because
  nothing sealed was ever written. Rows carry the `erasure_scope_id` of
  their source so a reader can tell which facts now point at shredded
  content.

  ## Not audited, not archived

  `audit?: false` because this is an event log: auditing an append-only,
  chained log into the central audit log would record every fact twice.
  `archival?: false` and `lifecycle?: false` because a fact is never
  soft-deleted and has no lifecycle; the immutability trigger refuses
  `UPDATE` and `DELETE`.

  ## The simulation twin

  The macro also emits `AshEnterprise.BusinessEvents.Ledger.SimulationEvent`
  (own table, own chains). Nothing in this application writes or reads it
  yet; it is a plain resource generated by the package, not a platform
  resource, and nothing exposes it (ADR 0051, "Known gaps").
  """

  use AshEnterprise.Platform.Resource,
    domain: AshEnterprise.BusinessEvents,
    ownership: :user_owned,
    tenant?: true,
    audit?: false,
    archival?: false,
    lifecycle?: false,
    extra_extensions: [AshEvents.EventLog, AshDiscreteBusinessEvents.Ledger.Extension]

  use AshDiscreteBusinessEvents.Resources,
      {:ledger,
       repo: AshEnterprise.Repo,
       table: "business_events",
       simulation_table: "business_simulation_events",
       domain: AshEnterprise.BusinessEvents}

  # The macro sets the table and the chain/immutability statements; this block
  # only adds an index (the section needs its repo restated to validate).
  postgres do
    repo AshEnterprise.Repo

    custom_indexes do
      # The derivation reads a subject's history (`by_subject`) on every
      # write it derives from.
      index [:region, :subject_external_id, :sequence]
    end
  end

  changes do
    change AshEnterprise.BusinessEvents.Changes.StampOwner, on: [:create]
  end
end
