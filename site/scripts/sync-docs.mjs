#!/usr/bin/env node
/**
 * sync-docs.mjs — copy the repo-root `docs/` tree into the Starlight content
 * collection, injecting frontmatter and rewriting relative links as it goes.
 *
 * Why a copy rather than a symlink or a custom loader: Starlight needs
 * frontmatter (`title`, `description`, `sidebar.order`) that the source markdown
 * deliberately does not carry, and the source markdown links siblings as
 * `03-authorization-is-data.md` — a path that is correct on GitHub and wrong on
 * the site. Both problems are transformations, so we transform.
 *
 * Starlight has no `base` or `docsRoot` option: its content collection root is
 * the site root. To serve the docs at `/docs/*` the files must therefore live at
 * `src/content/docs/docs/**`, which is the doubled path below.
 *
 * This runs in CI (`npm run prebuild`). It is deliberately defensive and exits
 * non-zero if it ever rewrites a link to a page that does not exist in the
 * output tree — a dead link in generated docs is worse than a missing page.
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const posix = path.posix;

const SITE_DIR = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const REPO_ROOT = path.resolve(SITE_DIR, '..');
const DOCS_SRC = path.join(REPO_ROOT, 'docs');
const OUT_DIR = path.join(SITE_DIR, 'src', 'content', 'docs', 'docs');

/** Must match `base` in astro.config.mjs. Overridable so a fork can rehome it. */
const BASE = (process.env.SITE_BASE ?? '/ash_enterprise').replace(/\/+$/, '');
const DOCS_ROUTE = `${BASE}/docs`;
const GITHUB_BLOB = 'https://github.com/lukegalea/ash_enterprise/blob/main';
const GITHUB_TREE = 'https://github.com/lukegalea/ash_enterprise/tree/main';

/**
 * Raw research transcripts. Superseded by the plans in `docs/plans/`, and
 * `BPMN.md` alone is 1.2 MB of interview transcript. Explicitly not published.
 */
const SKIP = [/^AshStrangler\.md$/i, /^BPMN\.md$/i, /strangler fig migrations/i];

const isSkipped = (basename) => SKIP.some((re) => re.test(basename));

/** Directories copied wholesale, in sidebar order. */
const DIRS = [
  { dir: 'manifesto', label: 'Manifesto' },
  { dir: 'adr', label: 'Decision records' },
  { dir: 'plans', label: 'Plans' },
];

/**
 * Single files copied to the docs root, renamed to a lowercase route.
 * `docs/README.md` becomes the `/docs/` index when it exists; when it does not,
 * `landingPage()` below generates one.
 */
const ROOT_FILES = [
  { from: 'README.md', to: 'index.md', optional: true },
  { from: 'QUESTIONS.md', to: 'questions.md' },
  { from: 'ROADMAP.md', to: 'roadmap.md' },
  { from: 'COMPLIANCE.md', to: 'compliance.md' },
  { from: 'HANDOFF.md', to: 'handoff.md' },
];

/**
 * Filenames that become a directory index so `/docs/manifesto/` and
 * `/docs/adr/` are real pages rather than 404s.
 */
const INDEX_NAMES = new Set(['readme.md', '00-index.md', 'index.md']);

const GENERATED_BANNER =
  '<!-- Generated by site/scripts/sync-docs.mjs from the repo-root docs/ tree. Do not edit. -->';

// ---------------------------------------------------------------------------
// Manifest
// ---------------------------------------------------------------------------

/** @typedef {{ srcRel: string, outRel: string, group: string, order: number|null }} Entry */

async function buildManifest() {
  /** @type {Entry[]} */
  const entries = [];

  for (const { dir } of DIRS) {
    const abs = path.join(DOCS_SRC, dir);
    let names;
    try {
      names = await fs.readdir(abs);
    } catch (err) {
      throw new Error(`Expected docs directory ${posix.join('docs', dir)} to exist: ${err.message}`);
    }

    for (const name of names.sort()) {
      if (!name.toLowerCase().endsWith('.md')) continue;
      if (isSkipped(name)) continue;
      const outName = INDEX_NAMES.has(name.toLowerCase()) ? 'index.md' : name;
      entries.push({
        srcRel: posix.join('docs', dir, name),
        outRel: posix.join(dir, outName),
        group: dir,
        order: leadingNumber(name),
      });
    }
  }

  for (const { from, to, optional } of ROOT_FILES) {
    const abs = path.join(DOCS_SRC, from);
    if (!(await exists(abs))) {
      if (optional) continue;
      throw new Error(`Expected docs/${from} to exist`);
    }
    entries.push({
      srcRel: posix.join('docs', from),
      outRel: to,
      group: 'root',
      order: null,
    });
  }

  return entries;
}

/** `00-index.md` -> 0, `0008-foo.md` -> 8, `ash-strangler.md` -> null. */
function leadingNumber(name) {
  const m = /^(\d+)[-_]/.exec(name);
  return m ? Number.parseInt(m[1], 10) : null;
}

// ---------------------------------------------------------------------------
// Routes
// ---------------------------------------------------------------------------

/** `adr/0008-x.md` -> `/ash_enterprise/docs/adr/0008-x/`; `adr/index.md` -> `.../adr/`. */
function routeFor(outRel) {
  let slug = outRel.replace(/\.md$/i, '');
  if (slug === 'index') return `${DOCS_ROUTE}/`;
  if (slug.endsWith('/index')) slug = slug.slice(0, -'/index'.length);
  return `${DOCS_ROUTE}/${slug}/`;
}

// ---------------------------------------------------------------------------
// Frontmatter extraction
// ---------------------------------------------------------------------------

const HEADING_RE = /^#\s+(.+?)\s*$/;

function extractTitle(lines) {
  for (let i = 0; i < lines.length; i++) {
    const m = HEADING_RE.exec(lines[i]);
    if (m) {
      const rest = lines.slice(0, i).concat(lines.slice(i + 1));
      // Drop the blank line the heading left behind, so the body does not begin
      // with dead space.
      while (rest.length && rest[0].trim() === '') rest.shift();
      return { title: cleanInline(m[1]), lines: rest };
    }
    // Only look through leading blank lines / HTML comments; a `# ` further down
    // is a real section heading, not the document title.
    if (lines[i].trim() !== '' && !lines[i].trim().startsWith('<!--')) break;
  }
  return { title: null, lines };
}

/**
 * The first blockquote or the first paragraph, whichever comes first. Skips
 * headings, lists (ADRs open with a `- **Status:**` metadata list), tables,
 * code fences and HTML.
 */
function extractDescription(lines) {
  let inFence = false;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const trimmed = line.trim();

    if (/^(```|~~~)/.test(trimmed)) {
      inFence = !inFence;
      continue;
    }
    if (inFence || trimmed === '') continue;
    if (trimmed.startsWith('#')) continue;
    if (trimmed.startsWith('<')) continue;
    if (/^([-*+]\s|\d+[.)]\s)/.test(trimmed)) continue;
    if (trimmed.startsWith('|')) continue;

    const block = [];
    if (trimmed.startsWith('>')) {
      for (let j = i; j < lines.length && lines[j].trim().startsWith('>'); j++) {
        block.push(lines[j].trim().replace(/^>\s?/, ''));
      }
    } else {
      for (let j = i; j < lines.length && lines[j].trim() !== ''; j++) {
        block.push(lines[j].trim());
      }
    }

    const text = cleanInline(block.join(' '));
    if (text.length >= 20) return truncate(text, 180);
    // Too short to be useful (a stray label); keep looking past this block.
    i += block.length;
  }
  return null;
}

/** Strip the markdown that has no business in a `<title>` or `<meta>` tag. */
function cleanInline(text) {
  return text
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/(^|\s)[*_]([^*_]+)[*_](?=\s|$|[.,;:)])/g, '$1$2')
    .replace(/<[^>]+>/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function truncate(text, max) {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const space = cut.lastIndexOf(' ');
  return `${(space > max * 0.6 ? cut.slice(0, space) : cut).replace(/[\s.,;:—-]+$/, '')}…`;
}

/** JSON string escaping is a valid YAML double-quoted scalar. */
const yamlString = (value) => JSON.stringify(value);

// ---------------------------------------------------------------------------
// Link rewriting
// ---------------------------------------------------------------------------

const INLINE_LINK_RE = /\]\(\s*(<[^>]*>|[^()\s]+)((?:\s+(?:"[^"]*"|'[^']*'|\([^)]*\)))?)\s*\)/g;
const REF_DEF_RE = /^(\s{0,3}\[[^\]^][^\]]*\]:\s*)(\S+)(.*)$/;
const ABSOLUTE_RE = /^(?:[a-z][a-z0-9+.-]*:|\/\/)/i;

/**
 * Directory links (`../plans/`) have to land somewhere. Every synced directory
 * gets an index page — generated below if the source has no README — so the
 * directory route is always real.
 */
const dirRoutes = new Map([
  ['docs', `${DOCS_ROUTE}/`],
  ...DIRS.map(({ dir }) => [`docs/${dir}`, `${DOCS_ROUTE}/${dir}/`]),
]);

function splitTarget(target) {
  const bare = target.startsWith('<') && target.endsWith('>') ? target.slice(1, -1) : target;
  const hashAt = bare.indexOf('#');
  if (hashAt === -1) return { file: bare, hash: '' };
  return { file: bare.slice(0, hashAt), hash: bare.slice(hashAt) };
}

/**
 * @param {string} target raw link target from the markdown
 * @param {string} srcRel repo-relative path of the file the link lives in
 * @param {Map<string,string>} srcToOut
 * @param {{ dead: any[], repaired: any[], externalised: any[] }} report
 */
function rewriteTarget(target, srcRel, srcToOut, report) {
  if (ABSOLUTE_RE.test(target.replace(/^</, ''))) return null;

  const { file, hash } = splitTarget(target);
  if (file === '') return null; // anchor-only link, e.g. `#10-what-is-genuinely-hard`

  const joined = posix.normalize(posix.join(posix.dirname(srcRel), file));
  const resolved = joined.replace(/\/+$/, '');
  if (resolved.startsWith('..') || resolved === '') {
    report.dead.push({ srcRel, target, reason: 'escapes the repository root' });
    return null;
  }

  // A link to a directory: `../plans/`, `adr/`.
  if (!posix.basename(resolved).includes('.') || dirRoutes.has(resolved)) {
    const route = dirRoutes.get(resolved);
    if (route) return route + hash;
    if (repoDirs.has(resolved)) {
      report.externalised.push({ srcRel, target, to: `${resolved}/` });
      return `${GITHUB_TREE}/${resolved}${hash}`;
    }
    if (!fileExistsSync(resolved)) {
      report.dead.push({ srcRel, target, reason: `${resolved} does not exist in the repository` });
      return null;
    }
  }

  const isMarkdown = /\.md$/i.test(resolved);

  if (isMarkdown) {
    const outRel = srcToOut.get(resolved);
    if (outRel) return routeFor(outRel) + hash;

    // Repair: the target names a numbered document that has since been renamed
    // (`0010-ingestion.md` for what is now `0010-meltano-for-ingestion.md`).
    // Resolving by number is safe because the number is the document's identity.
    const repaired = repairByNumber(resolved, srcToOut);
    if (repaired) {
      report.repaired.push({ srcRel, target, resolvedTo: repaired.srcRel });
      return routeFor(repaired.outRel) + hash;
    }

    // A markdown file that exists but is deliberately not published (the raw
    // research transcripts): point at GitHub rather than break the link.
    if (isSkipped(posix.basename(resolved)) && fileExistsSync(resolved)) {
      report.externalised.push({ srcRel, target, to: resolved });
      return `${GITHUB_BLOB}/${resolved}${hash}`;
    }

    report.dead.push({ srcRel, target, reason: `no page generated for ${resolved}` });
    return null;
  }

  // Not markdown: a link into the source tree (`lib/…ex`, `docs/roadmap.json`).
  // These have no page on the site, so send readers to GitHub.
  if (!fileExistsSync(resolved)) {
    report.dead.push({ srcRel, target, reason: `${resolved} does not exist in the repository` });
    return null;
  }
  report.externalised.push({ srcRel, target, to: resolved });
  return `${GITHUB_BLOB}/${resolved}${hash}`;
}

function repairByNumber(resolved, srcToOut) {
  const dir = posix.dirname(resolved);
  const num = leadingNumber(posix.basename(resolved));
  if (num === null) return null;
  for (const [srcRel, outRel] of srcToOut) {
    if (posix.dirname(srcRel) !== dir) continue;
    if (leadingNumber(posix.basename(srcRel)) === num) return { srcRel, outRel };
  }
  return null;
}

/** Populated once up front so link checking stays synchronous. */
let repoFiles = new Set();
let repoDirs = new Set();
const fileExistsSync = (repoRelPath) => repoFiles.has(repoRelPath);

function rewriteLinks(body, srcRel, srcToOut, report) {
  let out = body.replace(INLINE_LINK_RE, (match, target, title) => {
    const next = rewriteTarget(target, srcRel, srcToOut, report);
    return next === null ? match : `](${next}${title || ''})`;
  });

  out = out
    .split('\n')
    .map((line) => {
      const m = REF_DEF_RE.exec(line);
      if (!m) return line;
      const next = rewriteTarget(m[2], srcRel, srcToOut, report);
      return next === null ? line : `${m[1]}${next}${m[3]}`;
    })
    .join('\n');

  return out;
}

// ---------------------------------------------------------------------------
// Generated docs landing page
// ---------------------------------------------------------------------------

function sortedGroup(entries, group) {
  return entries
    .filter((e) => e.group === group)
    .sort((a, b) => (a.order ?? 1e9) - (b.order ?? 1e9) || a.outRel.localeCompare(b.outRel));
}

/** A minimal landing page for a synced directory whose source has no README. */
function directoryIndex(dir, label, entries) {
  const rows = sortedGroup(entries, dir)
    .map((e) => `- [${e.title ?? e.outRel}](${routeFor(e.outRel)})`)
    .join('\n');

  return `---
title: ${yamlString(label)}
description: ${yamlString(`${label} for the Ash Enterprise reference application.`)}
sidebar:
  order: 0
---

${GENERATED_BANNER}

${rows}
`;
}

function landingPage(entries) {
  const section = (dir) =>
    sortedGroup(entries, dir).map((e) => `- [${e.title ?? e.outRel}](${routeFor(e.outRel)})`);

  return `---
title: "Documentation"
description: "The argument, the decisions and the plans behind this reference Ash/Phoenix enterprise application."
sidebar:
  order: 0
---

${GENERATED_BANNER}

Everything on this site is generated from the markdown in the repository's \`docs/\`
directory. The argument lives in the manifesto, the specific decisions in the
decision records, and the work not yet done in the plans.

## Start here

- [The enterprise checklist](${routeFor('questions.md')}) — every question an enterprise application has to answer, and this repository's answer to each.
- [Roadmap](${routeFor('roadmap.md')}) — what is decided but not built.
- [Handoff notes](${routeFor('handoff.md')}) — the state of the tree.

## Manifesto

${section('manifesto').join('\n')}

## Decision records

${section('adr').join('\n')}

## Plans

${section('plans').join('\n')}
`;
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function exists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function collectRepoFiles(dir, prefix, files, dirs) {
  const dirents = await fs.readdir(dir, { withFileTypes: true });
  for (const d of dirents) {
    if (d.name === '.git' || d.name === 'node_modules' || d.name === '_build' || d.name === 'deps')
      continue;
    if (d.name.startsWith('.devenv')) continue;
    const rel = prefix ? `${prefix}/${d.name}` : d.name;
    if (d.isDirectory()) {
      dirs.add(rel);
      await collectRepoFiles(path.join(dir, d.name), rel, files, dirs);
    } else {
      files.add(rel);
    }
  }
  return { files, dirs };
}

async function main() {
  if (!(await exists(DOCS_SRC))) {
    throw new Error(`No docs/ directory at ${DOCS_SRC}. Is this running from site/?`);
  }

  ({ files: repoFiles, dirs: repoDirs } = await collectRepoFiles(
    REPO_ROOT,
    '',
    new Set(),
    new Set(),
  ));

  const entries = await buildManifest();
  const srcToOut = new Map(entries.map((e) => [e.srcRel, e.outRel]));

  await fs.rm(OUT_DIR, { recursive: true, force: true });
  await fs.mkdir(OUT_DIR, { recursive: true });

  const report = { dead: [], repaired: [], externalised: [] };

  for (const entry of entries) {
    const raw = await fs.readFile(path.join(REPO_ROOT, entry.srcRel), 'utf8');
    if (/^---\r?\n/.test(raw)) {
      // The source markdown is not supposed to carry frontmatter; if it starts
      // to, injecting ours would produce two blocks.
      throw new Error(`${entry.srcRel} already has frontmatter — sync-docs would duplicate it`);
    }

    const { title, lines } = extractTitle(raw.split('\n'));
    entry.title = title ?? titleFromFilename(entry.srcRel);
    const description = extractDescription(lines);
    const body = rewriteLinks(lines.join('\n').replace(/^\n+/, ''), entry.srcRel, srcToOut, report);

    const fm = [`title: ${yamlString(entry.title)}`];
    if (description) fm.push(`description: ${yamlString(description)}`);
    if (entry.order !== null) fm.push('sidebar:', `  order: ${entry.order}`);

    const outPath = path.join(OUT_DIR, entry.outRel);
    await fs.mkdir(path.dirname(outPath), { recursive: true });
    await fs.writeFile(outPath, `---\n${fm.join('\n')}\n---\n\n${GENERATED_BANNER}\n\n${body}\n`);
  }

  // Every synced directory needs a real page at its route, because the source
  // markdown links directories (`../plans/`) and because a sidebar group whose
  // own URL 404s is a bug readers hit by deleting a path segment.
  const generatedIndexes = [];
  for (const { dir, label } of DIRS) {
    const outPath = path.join(OUT_DIR, dir, 'index.md');
    if (await exists(outPath)) continue;
    await fs.writeFile(outPath, directoryIndex(dir, label, entries));
    generatedIndexes.push(dir);
  }

  const indexPath = path.join(OUT_DIR, 'index.md');
  const generatedLanding = !(await exists(indexPath));
  if (generatedLanding) await fs.writeFile(indexPath, landingPage(entries));

  // ---- summary -----------------------------------------------------------
  const byGroup = new Map();
  for (const e of entries) byGroup.set(e.group, (byGroup.get(e.group) ?? 0) + 1);

  console.log(`sync-docs: ${entries.length} pages -> ${path.relative(SITE_DIR, OUT_DIR)}`);
  for (const [group, n] of byGroup) console.log(`  ${group.padEnd(10)} ${n}`);
  console.log(
    `  ${'index'.padEnd(10)} 1 (${generatedLanding ? 'generated landing page' : 'from docs/README.md'})`,
  );
  if (generatedIndexes.length) {
    console.log(`  generated directory index for: ${generatedIndexes.join(', ')}`);
  }

  if (report.externalised.length) {
    console.log(`sync-docs: ${report.externalised.length} link(s) sent to GitHub instead of a page`);
  }
  for (const r of report.repaired) {
    console.warn(`sync-docs: repaired stale link in ${r.srcRel}: ${r.target} -> ${r.resolvedTo}`);
  }

  if (report.dead.length) {
    console.error(`\nsync-docs: ${report.dead.length} dead link(s):`);
    for (const d of report.dead) console.error(`  ${d.srcRel}: ${d.target} — ${d.reason}`);
    console.error('\nFix the link in docs/, or add the target to the sync manifest.');
    process.exitCode = 1;
    return;
  }
}

function titleFromFilename(srcRel) {
  return posix
    .basename(srcRel, '.md')
    .replace(/^\d+[-_]/, '')
    .replace(/[-_]+/g, ' ')
    .replace(/^\w/, (c) => c.toUpperCase());
}

main().catch((err) => {
  console.error(`sync-docs failed: ${err.message}`);
  process.exitCode = 1;
});
