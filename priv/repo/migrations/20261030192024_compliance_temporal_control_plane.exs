  # The temporal primary key, then each plain unique index as an exclusion
  # over the period under the same name.
  defp temporal_key_up(table, identities) do
    execute("ALTER TABLE #{table} DROP CONSTRAINT #{table}_pkey")

    execute(
      "ALTER TABLE #{table} ADD CONSTRAINT #{table}_pkey PRIMARY KEY (id, valid_at WITHOUT OVERLAPS)"
    )

    for {name, columns} <- identities do
      execute("DROP INDEX IF EXISTS #{name}")

      execute(
        "ALTER TABLE #{table} ADD CONSTRAINT #{name} EXCLUDE USING gist (#{Enum.map_join(columns, ", ", &"#{&1} WITH =")}, valid_at WITH &&)"
      )
    end
  end

  # The reverse. With `collapse?`, each record keeps only its latest version
  # before the plain key and unique indexes come back, so they can hold what
  # is left.
  defp temporal_key_down(table, identities, collapse?: collapse?) do
    for {name, _columns} <- identities do
      execute("ALTER TABLE #{table} DROP CONSTRAINT #{name}")
    end

    if collapse? do
      execute("""
      DELETE FROM #{table} older USING #{table} newer
      WHERE older.id = newer.id AND lower(older.valid_at) < lower(newer.valid_at)
      """)
    end

    execute("ALTER TABLE #{table} DROP CONSTRAINT #{table}_pkey")
    execute("ALTER TABLE #{table} ADD CONSTRAINT #{table}_pkey PRIMARY KEY (id)")

    for {name, columns} <- identities do
      execute("CREATE UNIQUE INDEX #{name} ON #{table} (#{Enum.join(columns, ", ")})")
    end
  end
